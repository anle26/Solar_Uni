"""Evaluation & Baselines: rule-based taxonomy vs. unsupervised anomaly detectors."""

from __future__ import annotations

import plotly.graph_objects as go
import streamlit as st

from app.data import BASELINE_COMPARISON, PAPER_FIGURES_DIR
from app.ui import render_page_header, render_step_flow


render_page_header(
    "Methodology / Evaluation",
    "Evaluation & Baselines",
    "How the rule-based taxonomy compares to unsupervised anomaly detectors under injected faults.",
)

st.markdown("### Rule-based taxonomy vs. unsupervised baselines")
metric_display = BASELINE_COMPARISON.rename(
    columns={
        "method": "Method",
        "precision": "Precision",
        "recall": "Recall",
        "f1": "F1",
        "kappa": "Cohen's κ",
    }
)
st.dataframe(
    metric_display.style.format(
        {"Precision": "{:.2f}", "Recall": "{:.2f}", "F1": "{:.2f}", "Cohen's κ": "{:.2f}"}
    ),
    hide_index=True,
    width="stretch",
)

metric_chart = go.Figure()
for metric, color in (("f1", "#0d766e"), ("precision", "#93c01f"), ("recall", "#f4a621")):
    metric_chart.add_trace(
        go.Bar(
            x=BASELINE_COMPARISON["method"],
            y=BASELINE_COMPARISON[metric],
            name=metric.capitalize(),
            marker_color=color,
        )
    )
metric_chart.update_layout(
    height=340,
    barmode="group",
    legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="left", x=0),
    margin=dict(l=0, r=10, t=45, b=0),
    plot_bgcolor="rgba(0,0,0,0)",
    paper_bgcolor="rgba(0,0,0,0)",
)
metric_chart.update_yaxes(gridcolor="#e6eeeb", range=[0, 1.05])
st.plotly_chart(metric_chart, width="stretch", config={"displayModeBar": False})
st.caption(
    "Isolation Forest, One-Class SVM, and LOF are trained on the same "
    "five-feature space, scored across N=20 physics-informed synthetic-fault "
    "seeds; mean ± std reported in the paper."
)

st.markdown("### Precision–recall curves")
pr_curve_path = PAPER_FIGURES_DIR / "fig_06_pr_curves.png"
if pr_curve_path.exists():
    st.image(str(pr_curve_path), width="stretch")
    st.caption(
        "Generated by the reproducible pipeline (`python reproduce_all.py`); "
        "not recomputed live here since baseline fitting is expensive."
    )
else:
    st.info(
        "PR curve figure not found. Run `python reproduce_all.py` to "
        f"regenerate it at: {pr_curve_path}"
    )

st.markdown("### How faults are synthetically injected")
render_step_flow(
    [
        (
            "Total loss",
            "Zero both AC and DC power together on a random inverter/interval so the fault stays physically consistent.",
        ),
        (
            "Partial loss",
            "Scale AC and DC power down by the same factor, mimicking a partial string failure rather than a full outage.",
        ),
        (
            "Recompute derived features",
            "Efficiency and peer-average gaps are recalculated after injection so no stale, pre-fault value leaks into evaluation.",
        ),
        (
            "Score against ground truth",
            "Both the rule-based taxonomy and the UML baselines are scored against the known injected labels.",
        ),
    ]
)
st.write(
    "A drop in AC power is always paired with a proportional drop in DC "
    "power. Without that physical constraint, an unsupervised detector could "
    "trivially flag the injected point as an impossible outlier, unfairly "
    "inflating its apparent performance."
)

st.markdown("### Limitations — read before citing these numbers")
st.warning(
    "**Partial circularity.** The TOTAL_LOSS rule (AC power near zero under "
    "meaningful irradiance) closely mirrors how total-loss faults are "
    "injected. The perfect precision above is therefore a consistency "
    "check — proof the rule recovers faults matching its own physical "
    "assumptions — not evidence of detection power on independent, "
    "real-world faults.\n\n"
    "**No field-verified ground truth.** No O&M logs or repair records were "
    "available. Every metric on this page is computed against synthetic "
    "faults; validating against real, annotated faults remains future work."
)
